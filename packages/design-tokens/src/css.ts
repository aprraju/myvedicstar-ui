import {
  colors,
  type ColorScheme,
  elevation,
  fontFamily,
  fontSize,
  fontWeight,
  layout,
  lineHeight,
  motion,
  radius,
  spacing,
  touchTarget,
} from './tokens';

const kebab = (value: string) => value.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const rem = (px: number) => (px === 0 ? '0' : `${px / 16}rem`);

function colorVars(scheme: ColorScheme, indent: string): string {
  return Object.entries(scheme)
    .map(([name, value]) => `${indent}--color-${kebab(name)}: ${value};`)
    .join('\n');
}

function vars(
  prefix: string,
  values: Record<string, string | number>,
  format: (v: never) => string = String,
): string {
  return Object.entries(values)
    .map(([name, value]) => `  --${prefix}-${kebab(name)}: ${format(value as never)};`)
    .join('\n');
}

/**
 * Generates the web stylesheet of CSS custom properties. The committed `css/tokens.css` must equal this output
 * (enforced by a test); regenerate with `npm run tokens:css`.
 *
 * Theme selection: `prefers-color-scheme` by default; `data-theme="light|dark"` on <html> overrides it. No inline
 * script is needed, which keeps the Content-Security-Policy strict.
 */
export function generateTokensCss(): string {
  return `/* Generated by @myvedicstar/design-tokens — do not edit. Run \`npm run tokens:css\`. */
:root {
  color-scheme: light dark;
${colorVars(colors.light, '  ')}
${vars('space', spacing, rem)}
${vars('font-size', fontSize, rem)}
${vars('font-weight', fontWeight)}
${vars('line-height', lineHeight)}
${vars('radius', radius, (v: number) => `${v}px`)}
${vars('shadow', Object.fromEntries(Object.entries(elevation).map(([k, v]) => [k, v.css])))}
${vars('touch-target', touchTarget, (v: number) => `${v}px`)}
${vars('duration', { fast: motion.durationFast, medium: motion.durationMedium, slow: motion.durationSlow }, (v: number) => `${v}ms`)}
  --easing-standard: ${motion.easingStandard};
  --font-sans: ${fontFamily.sans};
  --font-serif: ${fontFamily.serif};
  --font-mono: ${fontFamily.mono};
  --content-max-width: ${rem(layout.contentMaxWidth)};
  --readable-max-width: ${layout.readableMaxCh}ch;
  --gutter: ${rem(layout.gutter.compact)};
}

@media (min-width: 600px) {
  :root {
    --gutter: ${rem(layout.gutter.medium)};
  }
}

@media (min-width: 840px) {
  :root {
    --gutter: ${rem(layout.gutter.expanded)};
  }
}

:root[data-theme='light'] {
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${colorVars(colors.dark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${colorVars(colors.dark, '  ')}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0ms;
    --duration-medium: 0ms;
    --duration-slow: 0ms;
  }
}
`;
}
