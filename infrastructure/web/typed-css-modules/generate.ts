#!/usr/bin/env tsx
/**
 * Generates a TypeScript declaration for every CSS module (ui#127).
 *
 * Why: `vite/client.d.ts` declares CSS modules as `{ readonly [key: string]: string }`. That index signature tells
 * TypeScript every class exists, so `styles.typo` type-checks and `className={undefined}` renders silently. ui#125's
 * guard catches that at TEST time; this makes it an error at AUTHORING time, in every editor.
 *
 * Why a local script rather than a dependency: the repo already ships `tsx`, and ui#125's parser is already proven.
 * A new package would be another supply-chain surface for about eighty lines of parsing.
 *
 * Output is git-ignored on purpose. A committed declaration is a second source that drifts: edit the CSS, forget the
 * generator, and the declaration LIES about a class that no longer exists - worse than having none.
 *
 * Exits non-zero on any failure. A generator that fails silently leaves TypeScript on the permissive fallback:
 * exactly as unsafe as before, but looking protected. Loud failure is the whole point.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const WEB_SRC = resolve(import.meta.dirname, '../../../apps/web/src');

/** Recursively collect files under `dir` whose name ends with `suffix`. */
function walk(dir: string, suffix: string): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...walk(full, suffix));
    } else if (entry.name.endsWith(suffix)) {
      found.push(full);
    }
  }
  return found;
}

/**
 * Class names a CSS module exports.
 *
 * A class is exported if it appears in the selector position of any rule at any depth: indented blocks are ordinary
 * rules inside `@media`/`@supports`, and `.parent .child { }` defines BOTH. Reading only top-level selectors reports
 * false positives; ui#125 established that by measurement.
 *
 * Excluded: text inside a declaration block, and `:global(...)` content, which CSS modules does not export.
 */
function exportedClasses(css: string): string[] {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const names = new Set<string>();
  let buffer = '';
  let inGlobal = 0;

  for (let index = 0; index < withoutComments.length; index += 1) {
    const character = withoutComments[index];
    if (character === '{') {
      for (const match of buffer.matchAll(/(?<![\w-])\.(-?[A-Za-z_][A-Za-z0-9_-]*)/g)) {
        if (inGlobal === 0) {
          names.add(match[1] as string);
        }
      }
      buffer = '';
    } else if (character === '}') {
      buffer = '';
    } else if (character === ';') {
      buffer = buffer.replace(/[^{]*$/, '');
    } else {
      buffer += character;
    }

    if (withoutComments.startsWith(':global(', index)) {
      inGlobal += 1;
      index += ':global('.length - 1;
    } else if (character === ')' && inGlobal > 0) {
      inGlobal -= 1;
    }
  }

  return [...names].sort();
}

const modules = walk(WEB_SRC, '.module.css');
if (modules.length === 0) {
  console.error(
    'typed-css-modules: found no .module.css files under apps/web/src. Refusing to emit nothing.',
  );
  process.exit(1);
}

let emitted = 0;
for (const modulePath of modules) {
  const classes = exportedClasses(readFileSync(modulePath, 'utf8'));
  if (classes.length === 0) {
    console.error(
      'typed-css-modules: ' +
        relative(WEB_SRC, modulePath) +
        ' defines no classes. Either it is empty or the parser is',
    );
    console.error(
      'reading it wrong; emitting an empty declaration would silently disable typing for this module.',
    );
    process.exit(1);
  }

  const declaration = [
    '// Generated by infrastructure/web/typed-css-modules/generate.ts (ui#127). Do not edit; do not commit.',
    'declare const classes: {',
    ...classes.map((name) => "  readonly '" + name + "': string;"),
    '};',
    'export default classes;',
    '',
  ].join('\n');

  writeFileSync(modulePath + '.d.ts', declaration, 'utf8');
  emitted += 1;
}

console.warn('typed-css-modules: wrote ' + emitted + ' declaration(s) for ' + modules.length + ' module(s).');
